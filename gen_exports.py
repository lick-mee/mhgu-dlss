# Writes src/exports.S: every export of the system vulkan-1.dll as a jump through
# real_<name>, filled in by proxy.c. Functions proxy.c implements itself are skipped.
import pefile, re, sys
HOOKED = {n for l in open('src/proxy.c', encoding='utf-8') if l.startswith('// HOOKS:') for n in l.split()[2:]}
pe = pefile.PE('C:/Windows/System32/vulkan-1.dll'); pe.parse_data_directories()
names = sorted(s.name.decode() for s in pe.DIRECTORY_ENTRY_EXPORT.symbols if s.name)
with open('src/exports.S', 'w', encoding='utf-8', newline='\n') as f:
    f.write('# generated by gen_exports.py\n.data\n.globl proxy_names\nproxy_names:\n')
    for n in names: f.write(f'  .quad name_{n}\n')
    f.write('  .quad 0\n.globl proxy_reals\nproxy_reals:\n')
    for n in names: f.write(f'real_{n}: .quad 0\n')
    f.write('.section .rdata\n')
    for n in names: f.write(f'name_{n}: .asciz "{n}"\n')
    f.write('.text\n')
    for n in names:
        if n in HOOKED: continue
        f.write(f'.globl {n}\n{n}: jmp *real_{n}(%rip)\n')
    f.write('.section .drectve,"yni"\n')
    for n in names: f.write(f'  .ascii " -export:{n}"\n')
print(len(names), 'exports,', len(HOOKED), 'hooked')
