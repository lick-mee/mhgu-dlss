# Compiles shaders/*.comp to SPIR-V with the game's libshaderc_shared.dll and writes src/shaders.h.
import ctypes, os, sys, glob
here = os.path.dirname(os.path.abspath(__file__))
game = os.path.dirname(os.path.dirname(here))
os.add_dll_directory(game)
sc = ctypes.CDLL(os.path.join(game, 'libshaderc_shared.dll'))
for f, r in [('shaderc_compiler_initialize', ctypes.c_void_p), ('shaderc_compile_options_initialize', ctypes.c_void_p),
             ('shaderc_compile_into_spv', ctypes.c_void_p), ('shaderc_result_get_length', ctypes.c_size_t),
             ('shaderc_result_get_bytes', ctypes.c_void_p), ('shaderc_result_get_error_message', ctypes.c_char_p),
             ('shaderc_result_get_compilation_status', ctypes.c_int)]:
    getattr(sc, f).restype = r
sc.shaderc_compile_into_spv.argtypes = [ctypes.c_void_p, ctypes.c_char_p, ctypes.c_size_t, ctypes.c_int,
                                        ctypes.c_char_p, ctypes.c_char_p, ctypes.c_void_p]
for f in ['shaderc_result_get_length', 'shaderc_result_get_bytes', 'shaderc_result_get_error_message',
          'shaderc_result_get_compilation_status']:
    getattr(sc, f).argtypes = [ctypes.c_void_p]
sc.shaderc_compile_options_set_optimization_level.argtypes = [ctypes.c_void_p, ctypes.c_int]
comp = sc.shaderc_compiler_initialize()
opts = sc.shaderc_compile_options_initialize()
sc.shaderc_compile_options_set_optimization_level(opts, 2)  # performance
out = ['// generated by shaders/compile.py from shaders/*.comp\n#pragma once\n#include <stdint.h>\n']
for path in sorted(glob.glob(os.path.join(here, '*.comp'))):
    src = open(path, 'rb').read()
    name = os.path.splitext(os.path.basename(path))[0]
    res = sc.shaderc_compile_into_spv(comp, src, len(src), 2, os.path.basename(path).encode(), b'main', opts)
    if sc.shaderc_result_get_compilation_status(res) != 0:
        sys.exit(sc.shaderc_result_get_error_message(res).decode())
    n = sc.shaderc_result_get_length(res)
    data = ctypes.string_at(sc.shaderc_result_get_bytes(res), n)
    words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, n, 4)]
    out.append(f'static const uint32_t spv_{name}[{len(words)}] = {{\n')
    for i in range(0, len(words), 8):
        out.append('\t' + ', '.join(f'0x{w:08x}' for w in words[i:i + 8]) + ',\n')
    out.append('};\n')
    print(name, n, 'bytes')
open(os.path.join(os.path.dirname(here), 'src', 'shaders.h'), 'w', encoding='utf-8', newline='\n').write(''.join(out))
